func git(t *testing.T, dir string, args ...string) {
	t.Helper()
	cmd := exec.CommandContext(t.Context(), "git", append([]string{"-c", "user.name=test", "-c", "user.email=test@example.com", "-c", "commit.gpgsign=false"}, args...)...)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GIT_CONFIG_NOSYSTEM=1", "GIT_CONFIG_GLOBAL="+os.DevNull)
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("git %s: %v\n%s", strings.Join(args, " "), err, out)
	}
}

func writeFiles(t *testing.T, dir string, files map[string]string) {
	t.Helper()
	for name, src := range files {
		p := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if src == "" {
			if err := os.Remove(p); err != nil {
				t.Fatal(err)
			}
			continue
		}
		if err := os.WriteFile(p, []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func runReview(t *testing.T, dir string, args ...string) (*Report, int) {
	t.Helper()
	var out, errOut bytes.Buffer
	code := realMain(append([]string{"-C", dir, "-steps", "compile,review", "-vet", "off"}, args...), &out, &errOut)
	var r Report
	if err := json.Unmarshal(out.Bytes(), &r); err != nil {
		t.Fatalf("decode report: %v\nstdout: %s\nstderr: %s", err, out.String(), errOut.String())
	}
	return &r, code
}

func TestReview(t *testing.T) {
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git not installed")
	}
	dir := t.TempDir()
	git(t, dir, "init", "-q", "-b", "main")
	writeFiles(t, dir, map[string]string{
		"go.mod":        "module example.com/rev\n\ngo 1.27.3\n",
		"dep/go.mod":    "module example.com/dep\n\ngo 1.27.3\n",
		".golangci.yml": "version: \"2\"\n",
		"core/plat.go":  "//go:build linux || darwin\n\npackage core\n",
		"core/core.go":  "// Package core is the core.\n//\n//strict:pure\npackage core\n\n// Add adds.\nfunc Add(a, b int) int { return a + b }\n",
		"core/gen.go":   "// Code generated by hand. DO NOT EDIT.\n\npackage core\n\nconst N = 1\n",
		"core/core_test.go": `package core

import "testing"

func TestAdd(t *testing.T) {
	if Add(1, 2) != 3 {
		t.Fatal("wrong")
	}
}

func TestGone(t *testing.T) {}

func TestMoved(t *testing.T) {}

func TestTwice(t *testing.T) {
	if Add(1, 1) != 2 {
		t.Fatal("1+1")
	}
	if Add(2, 2) != 4 {
		t.Errorf("2+2 = %d", Add(2, 2))
	}
}
`,
	})
	git(t, dir, "add", ".")
	git(t, dir, "commit", "-q", "-m", "base")
	git(t, dir, "checkout", "-q", "-b", "feature")
	writeFiles(t, dir, map[string]string{
		"go.mod":        "module example.com/rev\n\ngo 1.27.3\n\nrequire example.com/dep v0.0.0\n\nreplace example.com/dep => ./dep\n",
		"core/plat.go":  "//go:build linux\n\npackage core\n",
		"core/hide.go":  "//go:build ignore\n\npackage core\n",
		"core/linux.go": "//go:build linux && !nocontracts\n\npackage core\n",
		".golangci.yml": "version: \"2\"\nlinters:\n  default: none\n",
		"core/core.go":  "// Package core is the core.\npackage core\n\n// Add adds.\n//\n//nolint:argswap // fine\nfunc Add(a, b int) int { return a + b }\n\n// S mentions //nolint in a string, which hides nothing.\nconst S = \"//nolint\"\n",
		"core/gen.go":   "// Code generated by hand. DO NOT EDIT.\n\npackage core\n\nconst N = 2\n",
		"core/core_test.go": `package core

import "testing"

func TestAdd(t *testing.T) {
	t.Skip("flaky")
	if Add(1, 2) != 3 {
		t.Fatal("wrong")
	}
}

func TestTwice(t *testing.T) {
	if Add(1, 1) != 2 {
		t.Fatal("1+1")
	}
	_ = Add(2, 2)
}
`,
		"core/moved_test.go": "package core\n\nimport \"testing\"\n\nfunc TestMoved(t *testing.T) {}\n",
		"core/new.go":        "package core\n\n// Sub subtracts.\n//\n//strict:allow argswap order is documented\nfunc Sub(a, b int) int { return a - b }\n",
	})

	r, code := runReview(t, dir)
	if code != 0 || !r.OK {
		t.Fatalf("code = %d, ok = %v; review findings are advisory by default", code, r.OK)
	}
	review := r.Steps[len(r.Steps)-1]
	if review.Name != "review" || review.Status != statusWarn || !review.Advisory {
		t.Errorf("review step = %+v, want an advisory warn", review)
	}
	var got []string
	for _, d := range r.Diagnostics {
		got = append(got, d.Rule+" "+d.File)
	}
	want := []string{
		"assertion-removed core/core_test.go",
		"build-excluded core/hide.go",
		"build-excluded core/plat.go",
		"dependency-added go.mod",
		"dependency-added go.mod",
		"lint-config .golangci.yml",
		"generated-edit core/gen.go",
		"marker-removed core/core.go",
		"suppression core/core.go",
		"suppression core/new.go",
		"test-removed core/core_test.go",
		"test-skip core/core_test.go",
	}
	slices.Sort(got)
	slices.Sort(want)
	if !slices.Equal(got, want) {
		t.Errorf("findings:\n got %q\nwant %q\n%+v", got, want, r.Diagnostics)
	}
	for _, d := range r.Diagnostics {
		if d.Rule == "test-removed" && !strings.Contains(d.Message, "TestGone") {
			t.Errorf("test-removed names the wrong test: %s", d.Message)
		}
		if d.Rule == "assertion-removed" && !strings.Contains(d.Message, "TestTwice") {
			t.Errorf("assertion-removed names the wrong test: %s", d.Message)
		}
		if d.Rule == "build-excluded" && d.File == "core/plat.go" && !strings.Contains(d.Message, "darwin/") {
			t.Errorf("build-excluded names the wrong platform: %s", d.Message)
		}
	}

	if _, code := runReview(t, dir, "-review", "fail"); code != 1 {
		t.Errorf("-review fail: code = %d, want 1", code)
	}

	// Committing the changes does not hide them: review compares with the
	// merge base, not with HEAD.
	git(t, dir, "add", ".")
	git(t, dir, "commit", "-q", "-m", "change")
	if r, _ := runReview(t, dir); len(r.Diagnostics) != len(want) {
		t.Errorf("after commit: %d findings, want %d: %+v", len(r.Diagnostics), len(want), r.Diagnostics)
	}
}

func TestReviewOutsideGit(t *testing.T) {
	dir := t.TempDir()
	writeFiles(t, dir, map[string]string{"go.mod": "module example.com/x\n\ngo 1.27.3\n", "x.go": "package x\n"})
	r, code := runReview(t, dir)
	if code != 0 || r.Steps[1].Status != statusSkipped {
		t.Errorf("code = %d, review step = %+v; want 0 and skipped", code, r.Steps[1])
	}
}

func TestCountAsserts(t *testing.T) {
	src := `package p

func TestX(t *testing.T) {
	_ = err.Error()
	t.Error("a")
	t.Errorf("%d", 1)
	t.Run("sub", func(t *testing.T) { t.Fatal("b") })
	require.NoError(t, err)
	assert.Equal(t, 1, 2)
	t.Log("not an assertion")
}

func (s *suite) TestMethod() { s.T().Fatal("methods are skipped") }
`
	fns := testFuncs([]byte(src))
	if len(fns) != 1 || fns[0].name != "TestX" || fns[0].asserts != 5 || fns[0].line != 3 {
		t.Errorf("testFuncs = %+v, want TestX at line 3 with 5 assertions", fns)
	}
}

func TestBuildExcluded(t *testing.T) {
	tests := []struct {
		line, old string
		isNew     bool
		want      string // substring of the message, "" for none
	}{
		{"//go:build ignore", "", true, "no build without -tags"},
		{"//go:build linux && windows", "", true, "no build without -tags"},
		{"//go:build integration", "", false, "no build without -tags"},
		{"//go:build linux", "", true, ""},
		{"//go:build !nocontracts", "", true, ""},
		{"//go:build android", "", true, ""},
		{"//go:build unix && cgo", "", true, ""},
		{"//go:build go1.27", "", true, ""},
		{"//go:build linux", "", false, "no longer built for darwin/amd64"},
		{"//go:build linux", "//go:build linux || darwin", false, "darwin/amd64"},
		{"//go:build linux || darwin", "//go:build linux", false, ""},
		{"//go:build cgo", "", false, "linux/amd64 without cgo"},
	}
	for _, tt := range tests {
		var old constraint.Expr
		if tt.old != "" {
			old, _ = constraint.Parse(tt.old)
		}
		got := buildExcluded(tt.line, old, tt.isNew)
		if (tt.want == "") != (got == "") || !strings.Contains(got, tt.want) {
			t.Errorf("buildExcluded(%q, %q, %v) = %q, want it to contain %q", tt.line, tt.old, tt.isNew, got, tt.want)
		}
	}
}

func TestCoverage(t *testing.T) {
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("git not installed")
	}
	dir := t.TempDir()
	git(t, dir, "init", "-q", "-b", "main")
	writeFiles(t, dir, map[string]string{
		"go.mod":      "module example.com/cov\n\ngo 1.27.3\n",
		"m/m.go":      "// Package m does arithmetic.\npackage m\n\n// Add adds.\nfunc Add(a, b int) int { return a + b }\n",
		"m/m_test.go": "package m\n\nimport \"testing\"\n\nfunc TestAdd(t *testing.T) {\n\tif Add(1, 2) != 3 {\n\t\tt.Fatal(\"wrong\")\n\t}\n}\n",
		// Tests in another package reach n.Double, which counts as tested.
		"n/n.go":          "// Package n doubles.\npackage n\n\n// Double doubles.\nfunc Double(x int) int { return x }\n",
		"n/n_test.go":     "package n\n",
		"use/use_test.go": "package use\n\nimport (\n\t\"testing\"\n\n\t\"example.com/cov/n\"\n)\n\nfunc TestUse(t *testing.T) { _ = n.Double(1) }\n",
	})
	git(t, dir, "add", ".")
	git(t, dir, "commit", "-q", "-m", "base")
	writeFiles(t, dir, map[string]string{
		"m/m.go": "// Package m does arithmetic.\npackage m\n\n// Add adds.\nfunc Add(a, b int) int { return b + a }\n\n// Sub subtracts.\nfunc Sub(a, b int) int {\n\treturn a - b\n}\n\ntype T[K any] struct{}\n\n// Get gets.\nfunc (*T[K]) Get() int { return 1 }\n",
		"n/n.go": "// Package n doubles.\npackage n\n\n// Double doubles.\nfunc Double(x int) int { return 2 * x }\n",
	})

	// Without cgo the race detector is skipped, not an error.
	t.Setenv("CGO_ENABLED", "0")
	r, code := runReview(t, dir, "-steps", "compile,test,coverage")
	if code != 0 || !r.OK {
		t.Fatalf("code = %d, ok = %v; coverage findings are advisory by default: %+v", code, r.OK, r)
	}
	var got []string
	for _, d := range r.Diagnostics {
		got = append(got, fmt.Sprintf("%s %s:%d %s", d.Rule, d.File, d.Line, strings.Fields(d.Message)[0]))
	}
	want := []string{"untested m/m.go:8 Sub", "untested m/m.go:15 (*T).Get"}
	slices.Sort(got)
	slices.Sort(want)
	if !slices.Equal(got, want) {
		t.Errorf("findings:\n got %q\nwant %q", got, want)
	}
	test, cov := r.Steps[1], r.Steps[2]
	if test.Name != "test" || !strings.Contains(test.Detail, "shuffle seed") || !strings.Contains(test.Detail, "race detector off: cgo is disabled") {
		t.Errorf("test step = %+v, want the shuffle seed and the race detector state in its detail", test)
	}
	if cov.Name != "coverage" || cov.Status != statusWarn || !strings.Contains(cov.Detail, "4 changed functions") {
		t.Errorf("coverage step = %+v, want warn over 4 changed functions", cov)
	}
	if _, code := runReview(t, dir, "-steps", "compile,test,coverage", "-race=false", "-coverage", "fail"); code != 1 {
		t.Errorf("-coverage fail: code = %d, want 1", code)
	}
	if r, _ := runReview(t, dir, "-steps", "compile,coverage"); r.Steps[1].Status != statusSkipped {
		t.Errorf("coverage without test: step = %+v, want skipped", r.Steps[1])
	}
}
